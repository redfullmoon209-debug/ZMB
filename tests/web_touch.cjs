const { chromium } = require('playwright');
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

const base = path.resolve('build');
const types = { '.html': 'text/html', '.js': 'text/javascript', '.wasm': 'application/wasm', '.pck': 'application/octet-stream', '.png': 'image/png' };
const server = http.createServer((req, res) => {
  const pathname = new URL(req.url, 'http://localhost').pathname;
  const file = path.join(base, pathname === '/' ? 'index.html' : pathname.slice(1));
  if (!file.startsWith(base + path.sep) || !fs.existsSync(file)) { res.writeHead(404); return res.end(); }
  res.setHeader('Content-Type', types[path.extname(file)] || 'application/octet-stream');
  fs.createReadStream(file).pipe(res);
});

(async () => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch({headless:true,executablePath:process.env.ZMB_BROWSER_PATH || undefined,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page = await browser.newPage({viewport:{width:932,height:430},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  try {
    page.on('console', msg => console.log('BROWSER:',msg.type(),msg.text()));
    page.on('pageerror', err => console.log('BROWSER ERROR:',err.message));
    page.on('requestfailed', req => console.log('REQUEST FAILED:',req.url(), req.failure()));
    page.on('response', res => {if(res.status() >= 400) console.log('HTTP ERROR:',res.status(),res.url());});
    await page.goto(`http://127.0.0.1:${server.address().port}/?zmbtest=1`);
    console.log('Page loaded:',await page.title(),await page.locator('body').innerText());
    await page.waitForFunction(() => typeof window.zmbDiagnosticsJSON==='string' && JSON.parse(window.zmbDiagnosticsJSON).controls.START, null, {timeout:30000});
    const diag = () => page.evaluate(() => JSON.parse(window.zmbDiagnosticsJSON));
    const initial = await diag();
    assert.equal(initial.ready,true,'Web touch queue failed to initialize');
    const canvas = await page.locator('canvas').boundingBox();
    function point(rect,x=0.5,y=0.5,id=1) {
      return {x:canvas.x+(rect[0]+(rect[2]-rect[0])*x)*canvas.width,y:canvas.y+(rect[1]+(rect[3]-rect[1])*y)*canvas.height,id};
    }
    const start = point(initial.controls.START);
    await page.touchscreen.tap(start.x,start.y);
    await page.waitForFunction(() => JSON.parse(window.zmbDiagnosticsJSON).started);
    await page.waitForTimeout(350);
    const d = await diag();
    assert.equal(d.safe,true,'Player should start in Safe Zone');
    const menu = point(d.controls.MENU);
    await page.touchscreen.tap(menu.x,menu.y);
    await page.waitForFunction(()=>{const d=JSON.parse(window.zmbDiagnosticsJSON);return d.page==='Menu'&&Object.keys(d.menu_items).length===10;});
    const menuData = await diag();
    const order = ['Bag','Quest','Social','Trade','Market','Shop','Ranking','News','Map','Settings'];
    let lastX = 1.01;
    for(const key of order){const r=menuData.menu_items[key];assert.ok(r[0]<lastX&&r[0]>=0&&r[2]<=1&&r[3]<=1,`Menu ${key} is visible and right-to-left`);lastX=r[0];}
    const settings = point(menuData.menu_items.Settings);
    await page.touchscreen.tap(settings.x,settings.y);
    await page.waitForFunction(()=>{const d=JSON.parse(window.zmbDiagnosticsJSON);return d.page==='Settings'&&d.scroll_rect.length===4;});
    const modal = await diag();
    const modalPoint = point(modal.scroll_rect,0.1,0.75,9);
    const uiCdp = await page.context().newCDPSession(page);
    await uiCdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[modalPoint]});
    await uiCdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{...modalPoint,y:modalPoint.y-110}]});
    await page.waitForFunction(()=>JSON.parse(window.zmbDiagnosticsJSON).scroll_value>30);
    await uiCdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
    const scrollDown=(await diag()).scroll_value;
    const modalPoint2=point(modal.scroll_rect,0.1,0.25,10);
    await uiCdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[modalPoint2]});
    await uiCdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{...modalPoint2,y:modalPoint2.y+100}]});
    await page.waitForFunction(v=>JSON.parse(window.zmbDiagnosticsJSON).scroll_value<v-20,scrollDown);
    await uiCdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
    const close = point((await diag()).controls.CLOSE);
    await page.touchscreen.tap(close.x,close.y);
    await page.waitForFunction(()=>JSON.parse(window.zmbDiagnosticsJSON).page==='');
    console.log('PASS: ten visible right-to-left menu icons; select Settings and drag the list both ways on touch screen');
    const joy = point(d.controls['◉'],0.5,0.15,1);
    const jump = point(d.controls.JUMP,0.5,0.5,2);
    const cdp = await page.context().newCDPSession(page);
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[joy]});
    await page.waitForFunction(() => {const d=JSON.parse(window.zmbDiagnosticsJSON);return d.stick[1]<-0.5&&d.velocity[2]<-1;});
    console.log('Joystick moving:',await diag());
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[joy,jump]});
    await page.waitForFunction(() => {const d=JSON.parse(window.zmbDiagnosticsJSON);return d.touches===2&&d.stick[1]<-0.5&&d.position[1]>0.1&&d.velocity[2]<-1;}, null, {timeout:5000});
    console.log('PASS: actual Godot Web build moves and jumps with two simultaneous browser touches');
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
    await page.waitForFunction(() => JSON.parse(window.zmbDiagnosticsJSON).stick.every(n=>n===0));
    await page.waitForFunction(() => JSON.parse(window.zmbDiagnosticsJSON).position[1]<0.05);
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[joy]});
    await page.waitForFunction(() => {const d=JSON.parse(window.zmbDiagnosticsJSON);return !d.safe&&d.position[2]<-13;},null,{timeout:20000});
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
    console.log('PASS: player spawns inside safe village and can walk freely through north gate to hunting grounds');
    await page.waitForFunction(() => JSON.parse(window.zmbDiagnosticsJSON).stick.every(n=>n===0));
    const initialCamera = await diag();
    assert.equal(initialCamera.camera_follow,false);
    const swipe = {x:canvas.x+canvas.width*0.56,y:canvas.y+canvas.height*0.40,id:2};
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[joy]});
    await page.waitForFunction(() => JSON.parse(window.zmbDiagnosticsJSON).stick[1]<-0.5);
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[joy,swipe]});
    const yawBefore=(await diag()).yaw;
    const right={...swipe,x:swipe.x+20};
    await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[joy,right]});
    const angleDiff=(a,b)=>Math.atan2(Math.sin(a-b),Math.cos(a-b));
    await page.waitForFunction(y=>{const d=JSON.parse(window.zmbDiagnosticsJSON);return Math.abs(Math.atan2(Math.sin(d.yaw-y),Math.cos(d.yaw-y)))>0.05;},yawBefore);
    const yawAfter=(await diag()).yaw;
    assert.ok(angleDiff(yawAfter,yawBefore)<0&&angleDiff(yawAfter,yawBefore)>-0.6,'Small right-finger drag must not jump camera heading');
    const joyMoved={...joy,x:joy.x+8};
    await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[joyMoved,right]});
    await page.waitForTimeout(300);
    assert.ok(Math.abs(angleDiff((await diag()).yaw,yawAfter))<0.01,'Moving joystick finger must not rotate camera');
    await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[joy,{...swipe,y:swipe.y-60}]});
    await page.waitForFunction(p => {const d=JSON.parse(window.zmbDiagnosticsJSON);return d.pitch>p+0.15&&d.stick[1]<-0.5;},initialCamera.pitch);
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
    const highPitch = (await diag()).pitch;
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[swipe]});
    await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{...swipe,y:swipe.y+60}]});
    await page.waitForFunction(p => JSON.parse(window.zmbDiagnosticsJSON).pitch<p-0.15,highPitch);
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
    const mode = point((await diag()).controls.CAMERA);
    await page.touchscreen.tap(mode.x,mode.y);
    await page.waitForFunction(()=>{const d=JSON.parse(window.zmbDiagnosticsJSON);return d.camera_follow&&Math.abs(Math.atan2(Math.sin(d.yaw-d.facing-Math.PI),Math.cos(d.yaw-d.facing-Math.PI)))<0.15;});
    await page.touchscreen.tap(mode.x,mode.y);
    await page.waitForFunction(()=>!JSON.parse(window.zmbDiagnosticsJSON).camera_follow);
    console.log('PASS: mobile vertical camera drag while moving, and toggle behind-player/free camera modes');
    const prePinch=await diag();
    assert.equal(prePinch.controls['+ ZOOM'],undefined);
    assert.equal(prePinch.controls['- ZOOM'],undefined);
    const pinchA={x:canvas.x+canvas.width*0.42,y:canvas.y+canvas.height*0.42,id:3};
    const pinchB={x:canvas.x+canvas.width*0.60,y:pinchA.y,id:4};
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[pinchA,pinchB]});
    await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[pinchA,{...pinchB,x:pinchB.x+canvas.width*0.10}]});
    await page.waitForFunction(z=>JSON.parse(window.zmbDiagnosticsJSON).zoom<z-0.5,prePinch.zoom);
    await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[pinchA,{...pinchB,x:pinchB.x-canvas.width*0.06}]});
    await page.waitForFunction(z=>JSON.parse(window.zmbDiagnosticsJSON).zoom>z+0.5,prePinch.zoom);
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
    console.log('PASS: browser two-finger pinch zoom in and out');
  } catch (error) {
    console.log('Failure state:',await page.evaluate(()=>({body:document.body.innerText,diagnostics:window.zmbDiagnosticsJSON,bridge:typeof window.zmbTouchDrain,ready:window.zmbTouchReady,gameplay:window.zmbGameplay,webgl2:!!document.createElement('canvas').getContext('webgl2'),canvas:document.querySelector('canvas')?.getBoundingClientRect().toJSON()})));
    throw error;
  } finally { await browser.close(); server.close(); }
})().catch(e=>{console.error(e);server.close();process.exitCode=1;});
